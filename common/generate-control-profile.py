from pathlib import Path
import json,hashlib
root=Path(__file__).resolve().parent.parent
p=json.loads((root/'common/control-profile.json').read_text(encoding='utf-8'))
normal,motor,fry=p['modes']
# This reviewed three-mode encoder is intentionally not a generic range unlocker.
# A different envelope needs an explicit implementation and new byte/behavior checks.
assert p['version']==2 and p['deviceModel']=='xiaomi-c3'
assert (p['secondsMax'],p['temperatureMin'],p['temperatureMax'],p['speedRawMin'],p['speedRawMax'],p['speedRawStep'],p['temperatureUiStep'])==(7200,35,180,5,100,5,5)
assert (normal['id'],normal['native'],normal['secondsMin'],normal['secondsMax'],normal['temperatureMin'],normal['temperatureMax'],normal['temperatureStep'],normal['speedRawMin'],normal['speedRawMax'],normal['speedRawStep'],normal['oemModeId'])==('normal',1,1,7200,35,100,1,5,30,5,1)
assert normal['temperatureOff'] is True and normal['directions']==['clockwise','counterclockwise']
assert (motor['id'],motor['native'],motor['secondsMin'],motor['secondsMax'],motor['initialTemperatureBelow'],motor['runningTemperatureBelow'],motor['activeHeaterPower'],motor['oemModeId'])==('motor',2,1,300,60,60,0,6)
assert motor['temperatureValues']==[0] and motor['speedRawValues']==[5,10,15,20,25,30,40,50,60,70,80,90,100] and motor['directions']==['clockwise']
assert (fry['id'],fry['native'],fry['secondsMin'],fry['secondsMax'],fry['temperatureMin'],fry['temperatureMax'],fry['temperatureStep'],fry['oemModeId'])==('fry',3,1,1800,100,180,5,5)
assert fry['speedRawValues']==[-10] and fry['directions']==['counterclockwise']
heat=p['heatOnly']
assert heat==dict(baseMode='normal',speedRaw=0,temperatureMin=35,temperatureMax=100,secondsMax=7200,scope='local-controls-only',physicalValidation='pending')
manual=p['localManual']
assert (manual['native'],manual['oemModeId'],manual['secondsMax'],manual['temperatureMax'],manual['reverseRawMax'],manual['forwardRawMax'],manual['highSpeedActualMax'])==(4,1,7200,150,100,100,80)
turbo=p['localTurbo']
assert (turbo['native'],turbo['command'],turbo['oemModeId'],turbo['secondsValues'],turbo['speedRawValues'],turbo['temperatureValues'],turbo['requiredVersions'])==(5,'START_TURBO',7,[1,2],[100,110,120],[0],[12,4,5])
